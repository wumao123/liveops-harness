const { chromium } = require('/Users/wumao/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', args: ['--disable-gpu'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  const checks = {};
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.accept());
  const base = process.env.LIVEOPS_TEST_URL || 'http://127.0.0.1:8775';
  await page.goto(base);
  await page.waitForFunction(() => document.querySelector('#runtime-metrics').children.length > 0);
  checks.runtimePanelLoaded = (await page.locator('#runtime-metrics').textContent()).includes('模型预算');
  async function command(text) {
    const waiting = page.waitForResponse(r => r.url().endsWith('/api/commands') && r.request().method() === 'POST');
    await page.locator('#instruction').fill(text);
    await page.locator('#send').click();
    const result = await (await waiting).json();
    await page.waitForFunction(() => !document.querySelector('#send').disabled);
    return result;
  }
  async function scene(value) {
    const waiting = page.waitForResponse(r => r.url().includes('/events') && r.request().method() === 'POST');
    await page.locator('#runtime-scene').selectOption(value);
    const result = await (await waiting).json();
    await page.waitForFunction(v => document.querySelector('#active-scene').textContent === v, { pre_live: '播前', on_live: '播中', post_live: '播后' }[value]);
    return result;
  }
  await scene('pre_live');
  checks.preLiveBlocksPriceWrites = (await command('把面霜价格改成119元')).status === 'blocked';
  await scene('on_live');
  const plan = await command('推荐三款开场商品');
  checks.planAvailable = plan.action.type === 'plan' && plan.status === 'ok';
  const feedbackResponse = page.waitForResponse(r => r.url().includes('/api/feedback/') && r.request().method() === 'POST');
  await page.locator('.advice-feedback button').filter({ hasText: '采纳建议' }).last().click();
  checks.feedbackIsNotExecution = (await (await feedbackResponse).json()).business_action_executed === false;
  await page.waitForFunction(() => document.querySelector('#runtime-metrics').textContent.includes('1/1'));
  checks.feedbackMetricsUpdated = true;
  await page.locator('#memory-scene').selectOption('on_live');
  await page.waitForFunction(() => !document.querySelector('#context-original').disabled);
  await page.locator('.memory-panel summary').click();
  await page.locator('#context-original').click();
  await page.waitForFunction(() => document.querySelector('#context-artifact').textContent.includes('command_id'));
  checks.fullContextArtifactReadable = true;
  await page.locator('#campaign-start').click();
  await page.waitForFunction(() => document.querySelector('#campaign-status').textContent.includes('已完成'), { timeout: 30000 });
  checks.threeMaterials = await page.locator('.material-item').count() === 3;
  await page.locator('.campaign-section summary').filter({ hasText: '商品变化与局部重规划' }).click();
  await page.locator('#replan-old').selectOption('SK-101');
  await page.locator('#replan-new').selectOption('SK-104');
  const waiting = page.waitForResponse(r => r.url().endsWith('/replan') && r.request().method() === 'POST');
  await page.locator('#campaign-replan').click();
  const revised = await (await waiting).json();
  checks.incrementalReplanPreservesFourTasks = revised.plan_revisions.at(-1).preserved_tasks.length === 4;
  await page.waitForFunction(() => !document.querySelector('#campaign-resume').disabled);
  await page.locator('#campaign-resume').click();
  await page.waitForFunction(() => document.querySelector('#campaign-status').textContent.includes('已完成'));
  await page.waitForFunction(() => document.querySelector('#campaign-materials').textContent.includes('玻尿酸精华'));
  checks.replannedMaterialsShown = true;
  checks.replanHistoryVisible = (await page.locator('#replan-history').textContent()).includes('复用 4');
  const observeResponse = page.waitForResponse(r => r.url().includes('/events') && r.request().method() === 'POST');
  await page.locator('#viewers').fill('1234');
  await page.locator('#observe-viewers').click();
  checks.audienceObservation = (await (await observeResponse).json()).audience.viewers === 1234;
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'outputs/article_harness_desktop_20261019.png', fullPage: true });
  checks.desktopNoHorizontalOverflow = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.goto(base);
  await mobile.waitForFunction(() => document.querySelector('#runtime-metrics').children.length > 0);
  checks.mobileNoHorizontalOverflow = await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
  checks.mobileRuntimeFits = await mobile.locator('.runtime-panel').evaluate(node => node.getBoundingClientRect().right <= innerWidth);
  await mobile.screenshot({ path: 'outputs/article_harness_mobile_20261019.png', fullPage: true });
  checks.noBrowserErrors = errors.length === 0;
  fs.writeFileSync('outputs/article_harness_ui_20261019.json', JSON.stringify({ scope: 'offline_real_browser_development_workflow_not_live_model_benchmark', checks, errors, allPassed: Object.values(checks).every(Boolean) }, null, 2));
  console.log(JSON.stringify({ checks, errors }));
  await browser.close();
  if (!Object.values(checks).every(Boolean)) process.exitCode = 1;
})().catch(error => { console.error(error); process.exitCode = 1; });
