const { chromium } = require('/Users/wumao/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  const checks = {};
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8775/');
  await page.waitForFunction(() => document.querySelector('#product-count').textContent.includes('5'));
  async function command(text) {
    const response = page.waitForResponse(r => r.url().endsWith('/api/commands') && r.request().method() === 'POST');
    await page.locator('#instruction').fill(text);
    await page.locator('#send').click();
    const result = await (await response).json();
    await page.waitForFunction(() => !document.querySelector('#send').disabled);
    return result;
  }
  const remembered = await command('记住：口播简短，不夸大功效');
  checks.preferenceSaved = remembered.status === 'ok' && (await page.locator('#memory-content').textContent()).includes('口播简短');
  const missing = await command('给面霜发10元券');
  checks.missingQuantityClarified = missing.status === 'clarification';
  await page.locator('#remote-fault').selectOption('lost_response');
  const fault = page.waitForResponse(r => r.url().endsWith('/api/simulator/remote-fault'));
  await page.locator('#set-remote-fault').click();
  await fault;
  const coupon = await command('给面霜发10元券20张');
  checks.approvalRequired = coupon.status === 'pending_approval';
  const approval = page.waitForResponse(r => r.url().endsWith('/approval'));
  await page.locator('.approval-actions .approve').last().click();
  const approved = await (await approval).json();
  checks.lostResponseBecomesUnknown = approved.status === 'unknown';
  await page.locator('#operations button').first().waitFor();
  const reconcile = page.waitForResponse(r => r.url().endsWith('/reconcile'));
  await page.locator('#operations button').first().click();
  const reconciled = await (await reconcile).json();
  checks.receiptReconciled = reconciled.status === 'ok';
  await page.waitForFunction(() => document.querySelector('#coupon-count').textContent === '1');
  checks.exactlyOneCouponBatch = (await (await page.request.get('http://127.0.0.1:8775/api/state/LIVE-DEMO-001')).json()).coupons.length === 1;
  await page.locator('#campaign-start').click();
  await page.locator('#campaign-pause:not([disabled])').waitFor();
  await page.locator('#campaign-pause').click();
  await page.waitForFunction(() => !document.querySelector('#campaign-resume').disabled, { timeout: 30000 });
  checks.pauseSavedCheckpoint = (await page.locator('#campaign-status').textContent()) === '已暂停';
  await page.locator('#campaign-resume').click();
  await page.waitForFunction(() => document.querySelector('#campaign-status').textContent === '已完成', { timeout: 60000 });
  await page.locator('.material-item').nth(2).waitFor();
  checks.preparationEightTasks = await page.locator('.task-item').count() === 8;
  checks.preparationThreeMaterials = await page.locator('.material-item').count() === 3;
  checks.exportAvailable = await page.locator('#campaign-export').isEnabled();
  await page.reload();
  await page.locator('.material-item').nth(2).waitFor();
  checks.materialsRestoredAfterReload = await page.locator('.material-item').count() === 3;
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#forget-preference').click();
  await page.waitForFunction(() => document.querySelector('#forget-preference').disabled);
  checks.preferenceDeletion = (await page.locator('#memory-content').textContent()).includes('尚未保存');
  await page.screenshot({ path: 'outputs/ui_upgrade_desktop_verified.png', fullPage: true });
  checks.desktopNoOverflow = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await mobile.goto('http://127.0.0.1:8775/');
  await mobile.waitForFunction(() => document.querySelector('#product-count').textContent.includes('5'));
  await mobile.screenshot({ path: 'outputs/ui_upgrade_mobile_verified.png', fullPage: true });
  checks.mobileNoOverflow = await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
  checks.noBrowserErrors = errors.length === 0;
  const report = { checks, errors, passed: Object.values(checks).filter(Boolean).length, total: Object.keys(checks).length };
  fs.writeFileSync('outputs/ui_upgrade_verified_20261019.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
  await browser.close();
  if (report.passed !== report.total) process.exitCode = 1;
})().catch(error => { console.error(error); process.exit(1); });
